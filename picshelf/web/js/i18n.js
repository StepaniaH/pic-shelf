const SUPPORTED = ["zh", "en"];

function detect() {
  let saved;
  try { saved = localStorage.getItem("picshelf.lang"); } catch { /* Use browser language. */ }
  if (SUPPORTED.includes(saved)) return saved;
  return (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
}

let locale = detect();

export function getLocale() {
  return locale;
}

export function setLocale(l) {
  locale = SUPPORTED.includes(l) ? l : "en";
  try { localStorage.setItem("picshelf.lang", locale); } catch { /* Apply in memory. */ }
}

export function toggleLocale() {
  setLocale(locale === "zh" ? "en" : "zh");
  return locale;
}

export function t(msgid, vars) {
  let s = locale === "zh" ? msgid : (EN[msgid] ?? msgid);
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split(`{${k}}`).join(String(vars[k]));
    }
  }
  return s;
}
